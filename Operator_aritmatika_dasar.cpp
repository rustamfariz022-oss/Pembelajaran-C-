#include <iostream>
using namespace std;

int main(){
    /*penggunaan operator penjumlahan(+)*/
    int a=18;
    int b=9;
    int hasil=a+b;
    cout<<"operator penjumlahan"<<endl;
    cout<<a<<"+"<<b<<"="<<hasil<<endl;   //hasilnya adalah 13//
    cout<<"--------------------------------"<<endl;
    
    /*Operator pengurangan*/
    int c=18;
    int d=9;
    int hasil_2=c-d;
    cout<<"operator penngurangan"<<endl;
    cout<<a<<"+"<<b<<"="<<hasil_2<<endl;   //hasilnya adalah 9//
    return 0;
}