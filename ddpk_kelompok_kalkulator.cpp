#include <iostream>
using namespace std;

int main() {
    int a, b;
    cout << "Angka pertama: ";
    cin >> a;
    cout << "Angka kedua: ";
    cin >> b;
    cout << "Penjumlahan = " << a + b << endl;
    cout << "Pengurangan = " << a - b << endl;
    cout << "Perkalian   = " << a * b << endl;
    cout << "Pembagian   = " << a / b << endl;

    return 0;
}
